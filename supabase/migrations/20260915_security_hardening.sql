begin;

-- The browser uses Supabase only for Auth and to read its own role. All other
-- application data must pass through the authorized backend.
alter table if exists public.users enable row level security;
alter table if exists public.shops enable row level security;
alter table if exists public.orders enable row level security;
alter table if exists public.assets enable row level security;
alter table if exists public.payment_receipts enable row level security;
alter table if exists public.notifications enable row level security;
alter table if exists public.admins enable row level security;

revoke all on table public.users from public, anon, authenticated;
revoke all on table public.shops from public, anon, authenticated;
revoke all on table public.orders from public, anon, authenticated;
revoke all on table public.assets from public, anon, authenticated;
revoke all on table public.payment_receipts from public, anon, authenticated;
revoke all on table public.notifications from public, anon, authenticated;
revoke all on table public.admins from public, anon, authenticated;

-- Storage is backend-mediated. Signed download URLs are created with the
-- service role; browser sessions cannot list, upload, overwrite, or delete.
revoke all on table storage.objects from public, anon, authenticated;
revoke all on table storage.buckets from public, anon, authenticated;

grant select (id, role) on table public.users to authenticated;
drop policy if exists users_read_own_profile on public.users;
create policy users_read_own_profile on public.users
  for select to authenticated
  using ((select auth.uid()) = id);

-- Trigger functions do not need to be directly callable by API roles.
do $$
begin
  if to_regprocedure('public.handle_new_user()') is not null then
    execute 'revoke all on function public.handle_new_user() from public, anon, authenticated';
  end if;
end
$$;

-- A durable claim prevents duplicate print dispatch across restarts and
-- multiple backend instances. A FAILED job releases the order for retry.
create table if not exists public.print_jobs (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  shop_id uuid not null references public.shops(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists print_jobs_one_active_per_order_idx
  on public.print_jobs(order_id)
  where status <> 'FAILED';
alter table public.print_jobs enable row level security;
revoke all on table public.print_jobs from public, anon, authenticated;

-- Remove access to any legacy generic SQL RPC. Such a function must never be
-- callable with the public anon key or an ordinary user session.
do $$
declare
  function_signature text;
begin
  for function_signature in
    select p.oid::regprocedure::text
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'query'
  loop
    execute format(
      'revoke all on function %s from public, anon, authenticated',
      function_signature
    );
  end loop;
end
$$;

commit;
