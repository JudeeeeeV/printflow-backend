begin;

-- Repair installations which deployed the spooler without its durable job table.
-- This is repeatable and does not change existing orders or print job records.
create table if not exists public.print_jobs (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  shop_id uuid not null references public.shops(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists print_jobs_one_active_per_order_idx
  on public.print_jobs(order_id) where status <> 'FAILED';

alter table public.print_jobs enable row level security;
revoke all on table public.print_jobs from public, anon, authenticated;
grant select, insert, update, delete on table public.print_jobs to service_role;
revoke all on sequence public.print_jobs_id_seq from public, anon, authenticated;
grant usage, select on sequence public.print_jobs_id_seq to service_role;

notify pgrst, 'reload schema';
commit;
